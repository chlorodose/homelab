#!/usr/bin/env python3
"""Publish a single-file HTML bundle onto www.lilith-aster.me.

Splits the bundle into a wrapper page at service/www/<page>/index.html and
content-addressed files at service/www/asserts/<sha256>.<ext> (embedded data:
URIs, the inline <style> and the inline <script>), prunes assets no longer
referenced by any page, and regenerates service/www/kustomization.yaml.

    scripts/www-bundle.py ~/Downloads/PAPERCLIP520.html PAPERCLIP520
    scripts/www-bundle.py --regen   # only prune assets and regenerate kustomization
"""
import base64
import hashlib
import re
import sys
from pathlib import Path

WWW = Path(__file__).resolve().parent.parent / "service" / "www"
ASSETS = WWW / "asserts"
PREFIX = "/asserts/"
EXT = {
    "image/webp": "webp",
    "image/png": "png",
    "image/jpeg": "jpg",
    "image/gif": "gif",
    "image/svg+xml": "svg",
    "font/woff2": "woff2",
    "font/woff": "woff",
    "audio/ogg": "ogg",
    "audio/mpeg": "mp3",
    "audio/wav": "wav",
}


def put(data: bytes, ext: str) -> str:
    name = f"{hashlib.sha256(data).hexdigest()}.{ext}"
    ASSETS.mkdir(parents=True, exist_ok=True)
    (ASSETS / name).write_bytes(data)
    return PREFIX + name


def split(bundle: Path, page: str) -> None:
    html = bundle.read_text(encoding="utf-8")
    html = re.sub(
        r"data:([\w/+.-]+);base64,([A-Za-z0-9+/=]+)",
        lambda m: put(base64.b64decode(m[2]), EXT[m[1]]),
        html,
    )

    html = re.sub(
        r"<style>\n?(.*?)</style>",
        lambda m: f'<link rel="stylesheet" href="{put(m[1].encode(), "css")}">',
        html,
        flags=re.S,
    )
    html = re.sub(
        r"<script>\n?(.*?)</script>",
        lambda m: f'<script src="{put(m[1].encode(), "js")}"></script>',
        html,
        flags=re.S,
    )

    out = WWW / page / "index.html"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(html, encoding="utf-8")


def prune() -> None:
    referenced: set[str] = set()
    pending = [p for p in WWW.rglob("*.html")]
    while pending:
        text = pending.pop().read_text(encoding="utf-8", errors="ignore")
        for name in re.findall(re.escape(PREFIX) + r"([0-9a-f]{64}\.\w+)", text):
            if name not in referenced:
                referenced.add(name)
                if name.endswith((".css", ".js")):
                    pending.append(ASSETS / name)
    for f in ASSETS.iterdir():
        if f.name not in referenced:
            f.unlink()


def regen() -> None:
    pages = sorted(p.parent.name for p in WWW.glob("*/index.html"))
    assets = sorted(f.name for f in ASSETS.iterdir())
    lines = [
        "# Generated by scripts/www-bundle.py; do not edit by hand.",
        "apiVersion: kustomize.config.k8s.io/v1beta1",
        "kind: Kustomization",
        "resources:",
        "  - www.yaml",
        "configMapGenerator:",
        "  - name: www-nginx",
        "    namespace: service",
        "    files:",
        "      - default.conf=nginx.conf",
        "  - name: www-root",
        "    namespace: service",
        "    files:",
        "      - index.html",
    ]
    for page in pages:
        lines += [
            f"  - name: www-page-{page.lower()}",
            "    namespace: service",
            "    files:",
            f"      - index.html={page}/index.html",
        ]
    lines += ["  - name: www-asserts", "    namespace: service", "    files:"]
    lines += [f"      - asserts/{a}" for a in assets]
    (WWW / "kustomization.yaml").write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    args = sys.argv[1:]
    if args == ["--regen"]:
        pass
    elif len(args) == 2:
        split(Path(args[0]).expanduser(), args[1])
    else:
        sys.exit(__doc__)
    prune()
    regen()


if __name__ == "__main__":
    main()
